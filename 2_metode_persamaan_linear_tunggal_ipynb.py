import matplotlib.pyplot as plt
import numpy as np

# ==========================================
# SOAL 1: y = 3x^3 - 5x^2 + 4x - 7, dengan y = 1
# Bentuk f(x) = 3x^3 - 5x^2 + 4x - 8 = 0
# ==========================================
x1 = np.linspace(0, 3, 400)
f1 = lambda x: 3*x**3 - 5*x**2 + 4*x - 8
y1 = f1(x1)

plt.figure(figsize=(7, 5))
plt.plot(x1, y1, 'b-', label='Kurva f1(x)')

# Menggambar sumbu x dan y
plt.plot([-1, 4], [0, 0], 'k-', linewidth=1)  # Sumbu X
plt.plot([0, 0], [-10, 15], 'k-', linewidth=1) # Sumbu Y

# Annotation (Menggunakan koordinat teks)
plt.text(1.2, 5, 'y = 3x^3-5x^2+4x-8', fontsize=10, color='blue')
plt.text(1.7, 0.5, 'Akar', fontsize=10, color='red', fontweight='bold')

plt.xlim(-1, 4)
plt.ylim(-10, 15)
plt.axhline(0, color='gray', linestyle='--', alpha=0.5)
plt.axvline(0, color='gray', linestyle='--', alpha=0.5)
plt.title('Grafik Penyelesaian Soal 1')
plt.xlabel('x')
plt.ylabel('f(x)')
plt.grid(True, alpha=0.3)
plt.show()


# ==========================================
# SOAL 2: y = e^x - x^2, dengan y = 0
# Bentuk f(x) = e^x - x^2 = 0
# ==========================================
x2 = np.linspace(-2, 2, 400)
f2 = lambda x: np.exp(x) - x**2
y2 = f2(x2)

plt.figure(figsize=(7, 5))
plt.plot(x2, y2, 'g-', label='Kurva f2(x)')

# Menggambar sumbu x dan y
plt.plot([-2, 2], [0, 0], 'k-', linewidth=1)  # Sumbu X
plt.plot([0, 0], [-2, 8], 'k-', linewidth=1)  # Sumbu Y

# Annotation
plt.text(-1.5, 4, 'y = e^x - x^2', fontsize=10, color='green')
plt.text(-0.7, 0.3, 'Akar', fontsize=10, color='red', fontweight='bold')

plt.xlim(-2, 2)
plt.ylim(-2, 8)
plt.axhline(0, color='gray', linestyle='--', alpha=0.5)
plt.axvline(0, color='gray', linestyle='--', alpha=0.5)
plt.title('Grafik Penyelesaian Soal 2')
plt.xlabel('x')
plt.ylabel('f(x)')
plt.grid(True, alpha=0.3)
plt.show()


# ==========================================
# SOAL 3: y = log(x + 2) + 2x - 3, dengan y = 0
# Catatan: log() di Python menggunakan log natural (ln)
# ==========================================
