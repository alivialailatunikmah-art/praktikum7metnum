import numpy as np

# ==========================================
# DEFINISI FUNGSI PERSAMAAN NON-LINEAR
# ==========================================
# 1. y = 3x^3 - 5x^2 + 4x - 7, dengan y = 1  -> f1(x) = 3x^3 - 5x^2 + 4x - 8 = 0
def f1(x):
    return 3 * x**3 - 5 * x**2 + 4 * x - 8

# 2. y = e^x - x^2, dengan y = 0  -> f2(x) = e^x - x^2 = 0
def f2(x):
    return np.exp(x) - x**2

# 3. y = log(x + 2) + 2x - 3, dengan y = 0  -> f3(x) = ln(x + 2) + 2x - 3 = 0
def f3(x):
    return np.log(x + 2) + 2 * x - 3


# ==========================================
# FUNGSI METODE REGULA FALSI (Konversi dari RegulaFalsi.m)
# ==========================================
def regula_falsi(f, a, b, n, tol):
    fa = f(a)
    fb = f(b)

    # Mengecek apakah fa dan fb memiliki tanda yang sama
    if fa * fb > 0:
        raise ValueError("Warning: sama tanda (tidak ada jaminan akar di antara keduanya).")

    print(f"\n{'Iter':<5} {'a':<10} {'b':<10} {'fa':<10} {'fb':<10} {'c':<10} {'fc':<10}")
    print("-" * 75)

    c = a
    for i in range(1, n + 1):
        # Rumus metode Regula Falsi
        if fb - fa == 0:
            break
        c = (a * fb - b * fa) / (fb - fa)
        fc = f(c)

        # Mencetak nilai iterasi
        print(f"{i:<5} {a:<10.5f} {b:<10.5f} {fa:<10.5f} {fb:<10.5f} {c:<10.5f} {fc:<10.5f}")

        # Menghentikan iterasi saat error mencapai batas toleransi
        if abs(c - a) <= tol or abs(c - b) <= tol:
            break

        # Jika fa atau fc bernilai 0 maka akar ditemukan
        if fa * fc == 0:
            break
        # Kondisi akar berada di antara a dan c
        elif fa * fc < 0:
            b = c
            fb = f(b)
        # Kondisi akar berada di antara b dan c
        else:
            a = c
            fa = f(a)

    return c


# ==========================================
# EKSEKUSI PERHITUNGAN UNTUK KETIGA SOAL
# ==========================================
max_iter = 20
toleransi = 0.0001

print("=" * 60)
print("1. PENYELESAIAN PERSAMAAN 1: 3x^3 - 5x^2 + 4x - 8 = 0")
print("=" * 60)
akar1 = regula_falsi(f1, a=1.5, b=2.5, n=max_iter, tol=toleransi)
print(f"\n>> Perkiraan Akar Persamaan 1 adalah: {akar1:.5f}\n")

print("=" * 60)
print("2. PENYELESAIAN PERSAMAAN 2: e^x - x^2 = 0")
print("=" * 60)
akar2 = regula_falsi(f2, a=-1.0, b=0.0, n=max_iter, tol=toleransi)
print(f"\n>> Perkiraan Akar Persamaan 2 adalah: {akar2:.5f}\n")

print("=" * 60)
print("3. PENYELESAIAN PERSAMAAN 3: log(x + 2) + 2x - 3 = 0")
print("=" * 60)
akar3 = regula_falsi(f3, a=0.5, b=1.0, n=max_iter, tol=toleransi)
print(f"\n>> Perkiraan Akar Persamaan 3 adalah: {akar3:.5f}\n")