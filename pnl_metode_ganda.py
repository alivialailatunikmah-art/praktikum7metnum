def bisection(func, a, b, tol=0.0001, max_iter=20):
    if func(a) * func(b) >= 0:
        return None, "Interval tidak valid (tidak ada perubahan tanda)."
    c = a
    for i in range(1, max_iter + 1):
        c = (a + b) / 2.0
        if func(c) == 0 or (b - a) / 2.0 < tol:
            return c, i
        if func(a) * func(c) < 0:
            b = c
        else:
            a = c
    return c, max_iter

def regula_falsi(func, a, b, tol=0.0001, max_iter=20):
    if func(a) * func(b) >= 0:
        return None, "Interval tidak valid (tidak ada perubahan tanda)."
    c = a
    for i in range(1, max_iter + 1):
        fa, fb = func(a), func(b)
        if fb - fa == 0:
            break
        c = b - (fb * (a - b)) / (fb - fa)
        if abs(func(c)) < tol or (b - a) / 2.0 < tol:
            return c, i
        if func(a) * func(c) < 0:
            b = c
        else:
            a = c
    return c, max_iter

